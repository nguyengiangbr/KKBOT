    // Helper methods
    public static int MakeLParam(int low, int high) => (high << 16) | (low & 0xFFFF);
    public static int MakeWParam(int low, int high) => (high << 16) | (low & 0xFFFF);
    public static int LoWord(int dwValue) => dwValue & 0xFFFF;
    public static int HiWord(int dwValue) => (dwValue >> 16) & 0xFFFF;
